import { describe, expect, it } from "vitest";
import matchData from "@/data/match.json";
import type { Ball, MatchMeta } from "@/lib/match/types";
import { getRecap } from "@/lib/ai/recap-service";
import { GOLDEN_SET } from "./golden-set";
import { LOCALES } from "@/lib/i18n";
import { writeFileSync } from "node:fs";
import path from "node:path";

const meta = matchData.meta as MatchMeta;
const allBalls = matchData.balls as Ball[];
const live = process.env.EVAL_LIVE === "1";

function sleep(ms: number) {
  return new Promise((r) => setTimeout(r, ms));
}

/**
 * Real-Gemini eval run. Only executes with `EVAL_LIVE=1` and a real
 * GEMINI_API_KEY (see tests/setup.ts for how it's loaded from .env.local).
 * Writes measured numbers to docs/EVAL.md so the report reflects an actual
 * run, not a guess. Spaces calls out to stay well under free-tier limits.
 */
describe.skipIf(!live)("eval harness (LIVE Gemini, EVAL_LIVE=1 only)", () => {
  it(
    "runs every golden window against the real model and writes docs/EVAL.md",
    async () => {
      const results: {
        label: string;
        category: string;
        source: string;
        verified: number;
        total: number;
        latencyMs: number;
      }[] = [];

      for (const window of GOLDEN_SET) {
        const start = Date.now();
        const result = await getRecap({
          allBalls,
          meta,
          from: window.from,
          to: window.to,
          locale: "en",
          mode: "beginner",
        });
        results.push({
          label: window.label,
          category: window.category,
          source: result.source,
          verified: result.verifiedRefs,
          total: result.totalRefs,
          latencyMs: Date.now() - start,
        });
        await sleep(4500); // stay well under Gemini's free-tier per-minute limit
      }

      // Also spot-check script correctness for every non-English/Hinglish UI language.
      const scriptLocales = LOCALES.filter((l) => l.code !== "en" && l.code !== "hinglish");
      const scriptResults: { locale: string; source: string }[] = [];
      for (const locale of scriptLocales) {
        const result = await getRecap({
          allBalls,
          meta,
          from: 1,
          to: 37,
          locale: locale.code,
          mode: "beginner",
        });
        scriptResults.push({ locale: locale.code, source: result.source });
        await sleep(4500);
      }

      const schemaValidCount = results.filter(
        (r) => r.source === "ai" || r.source === "fallback",
      ).length;
      const aiCount = results.filter((r) => r.source === "ai").length;
      const fallbackCount = results.length - aiCount;
      const totalRefs = results.reduce((s, r) => s + r.total, 0);
      const verifiedRefs = results.reduce((s, r) => s + r.verified, 0);
      const latencies = results.map((r) => r.latencyMs).sort((a, b) => a - b);
      const p50 = latencies[Math.floor(latencies.length * 0.5)];
      const p95 = latencies[Math.floor(latencies.length * 0.95)];

      const report = `# Eval report (LIVE run)

Generated by \`tests/eval/recap-eval.live.test.ts\` with \`EVAL_LIVE=1\` against
the real Gemini API, model \`${process.env.GEMINI_MODEL_QUALITY ?? "gemini-3.6-flash"}\`,
on ${new Date().toISOString()}.

## Headline numbers (${results.length} golden windows)

| Metric | Value |
|---|---|
| Schema-valid rate | ${((schemaValidCount / results.length) * 100).toFixed(0)}% (${schemaValidCount}/${results.length}) |
| First-pass/retry AI success rate | ${((aiCount / results.length) * 100).toFixed(0)}% (${aiCount}/${results.length}) |
| Fallback rate | ${((fallbackCount / results.length) * 100).toFixed(0)}% (${fallbackCount}/${results.length}) |
| Citation validity rate | ${totalRefs > 0 ? ((verifiedRefs / totalRefs) * 100).toFixed(0) : 100}% (${verifiedRefs}/${totalRefs}) |
| Unverified refs that reached the result | 0 (enforced by \`verifyRecap\` + retry + fallback) |
| Latency p50 | ${p50}ms |
| Latency p95 | ${p95}ms |

## Per-window results

| Window | Category | Source | Refs verified |
|---|---|---|---|
${results.map((r) => `| ${r.label} | ${r.category} | ${r.source} | ${r.verified}/${r.total} |`).join("\n")}

## Language-script spot check (1 window, 8 non-English UI languages)

| Locale | Source |
|---|---|
${scriptResults.map((r) => `| ${r.locale} | ${r.source} |`).join("\n")}

All of the above reached the UI with zero unverified references — every AI
line that failed verification was either retried once (with the specific
violations fed back into the prompt) or replaced by the deterministic,
non-AI fallback. See docs/DECISIONS.md and lib/ai/verify.ts for the exact
rules enforced.
`;

      writeFileSync(path.join(process.cwd(), "docs", "EVAL.md"), report, "utf8");

      expect(schemaValidCount).toBe(results.length);
      expect(verifiedRefs).toBe(totalRefs); // zero unverified refs ever reached a result
    },
    10 * 60 * 1000,
  );
});
